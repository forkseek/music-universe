import { chromium, expect } from '@playwright/test'
import { mkdirSync, writeFileSync } from 'node:fs'
import { dismissEntryGuide } from './entry-guide.mjs'
import { installUniverseFixture } from './universe-fixture.mjs'

const url = process.env.UNIVERSE_TEST_URL || 'http://127.0.0.1:5188/'
const output = 'tests/reports/universe-experience' + (url.includes('3002') ? '/hall' : '')
mkdirSync(output, { recursive: true })
const browser = await chromium.launch({ headless: true, args: ['--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1.5 })
const errors = [], results = []
page.on('pageerror', error => errors.push(error.message))
const { tracks } = await installUniverseFixture(page, url)
const scene = page.locator('.galaxy-viewport canvas').first(), audio = page.getByTestId('audio-engine')
const state = () => scene.evaluate(el => ({ ...el.dataset }))
const numeric = async key => Number((await state())[key])
const openEffects = async () => { if (!await page.locator('#universe-experience-menu').isVisible()) await page.getByRole('button', { name: '宇宙效果', exact: true }).click() }
const effects = async label => { await openEffects(); await page.locator('#universe-experience-menu').getByRole('button', { name: label, exact: true }).click() }
const closeEffects = async () => { if (await page.locator('#universe-experience-menu').isVisible()) await page.getByRole('button', { name: '关闭宇宙效果设置', exact: true }).click() }
const moving = async () => audio.evaluate(el => !el.paused && el.readyState >= 2)
const camera = async () => { const d = await state(); return [Number(d.cameraX), Number(d.cameraY), Number(d.cameraZ), ...JSON.parse(d.cameraQuaternion)] }
const samePose = (a, b) => expect(Math.max(...a.map((value, i) => Math.abs(value - b[i])))).toBeLessThan(.00001)
const wheelTo = async (target, direction) => {
  for (let i = 0; i < 12 && (direction < 0 ? await numeric('zoom') > target : await numeric('zoom') < target); i++) {
    await page.mouse.wheel(0, direction * 150); await page.waitForTimeout(180)
  }
}
const log = value => { results.push(value); console.log(JSON.stringify(value)) }
const overlap = (a, b) => a && b && a.x < b.x + b.width && a.x + a.width > b.x && a.y < b.y + b.height && a.y + a.height > b.y
try {
  await page.goto(url)
  await expect(scene).toHaveAttribute('data-frame-count', /\d+/, { timeout: 60000 })
  await dismissEntryGuide(page)
  await scene.evaluate(el => { window.__originalGalaxyCanvas = el })
  await expect.poll(() => page.locator('.planet-caption[data-focused="true"]').count()).toBe(0)
  const targets = JSON.parse((await state()).projectedTargets)
  const point = targets.find(target => target.id === tracks[1].id)
  await page.mouse.move(point.x, point.y)
  await expect(page.locator(`[data-scene-target="${tracks[1].id}"]`).locator('..')).toHaveAttribute('data-focused', 'true')
  await page.mouse.move(700, 60)
  await expect.poll(() => page.locator('.planet-caption[data-focused="true"]').count()).toBe(0)
  const brightness = await page.locator('.space-motion-backdrop').evaluate(el => getComputedStyle(el).filter)
  expect(brightness).toBe('brightness(0.84)')
  await page.screenshot({ path: `${output}/overview.png` })
  log({ focusLabels: true, background: brightness })

  await effects('静止'); await closeEffects()
  await page.getByRole('button', { name: '沉浸模式', exact: true }).click()
  await page.getByRole('button', { name: '播放星球歌曲', exact: true }).click()
  await expect.poll(moving, { timeout: 15000 }).toBe(true)
  await expect(scene).toHaveAttribute('data-audio-analysis', 'ready')
  await audio.evaluate(el => { el.currentTime = 3 })
  await expect.poll(() => numeric('audioLow')).toBeGreaterThan(.05)
  expect(await numeric('audioHigh')).toBeLessThan(.004)
  expect(await numeric('audioHaloGain')).toBeGreaterThan(1.003)
  expect(await numeric('audioHaloGain')).toBeLessThanOrEqual(1.07)
  await page.keyboard.press('u')
  await expect.poll(() => page.locator('.planet-caption[data-playing="true"][data-focused="true"]').count()).toBe(1)
  log({ actualBassResponse: true, low: await numeric('audioLow'), haloGain: await numeric('audioHaloGain') })

  await expect(page.getByTestId('lyric-caption')).toHaveAttribute('data-view-mode', 'overview')
  await expect(page.locator('.lyric-row')).toHaveCount(4)
  await page.mouse.move(190, 180)
  await wheelTo(.65, -1)
  await expect(page.getByTestId('lyric-caption')).toHaveAttribute('data-view-mode', 'near')
  await expect(page.locator('.lyric-row')).toHaveCount(2)
  await page.screenshot({ path: `${output}/near-lyrics.png` })
  await wheelTo(.95, 1)
  await expect(page.getByTestId('lyric-caption')).toHaveAttribute('data-view-mode', 'overview')
  await expect(page.locator('.lyric-row')).toHaveCount(4)
  log({ nearTwoRowsOverviewFour: true })

  await audio.evaluate(el => { el.currentTime = 3 })
  await expect.poll(() => numeric('audioLow')).toBeGreaterThan(.05)
  const beforePause = await numeric('audioLow')
  await audio.evaluate(el => el.pause())
  await page.waitForTimeout(180)
  const afterPause = await numeric('audioLow')
  expect(afterPause).toBeGreaterThan(0); expect(afterPause).toBeLessThan(beforePause)
  await expect.poll(() => numeric('audioLow'), { timeout: 10000 }).toBe(0)
  log({ smoothPauseDecay: true, beforePause, afterPause })
  await page.getByRole('button', { name: '播放星球歌曲', exact: true }).click()
  await audio.evaluate(el => { el.currentTime = 14 })
  await expect.poll(() => numeric('audioHigh'), { timeout: 8000 }).toBeGreaterThan(.003)
  await expect.poll(() => numeric('audioLow'), { timeout: 10000 }).toBe(0)
  expect(await numeric('audioDustGain')).toBeGreaterThan(1)
  log({ actualTrebleResponse: true, high: await numeric('audioHigh'), dustGain: await numeric('audioDustGain') })

  await effects('关闭'); await closeEffects()
  const beforeOffTime = await audio.evaluate(el => el.currentTime)
  await expect.poll(() => numeric('audioHigh'), { timeout: 10000 }).toBe(0)
  expect(await moving()).toBe(true)
  expect(await audio.evaluate(el => el.currentTime)).toBeGreaterThan(beforeOffTime)
  await effects('增强'); await closeEffects()
  await audio.evaluate(el => { el.currentTime = 3 })
  await expect.poll(() => numeric('audioLow')).toBeGreaterThan(.1)
  log({ effectOffKeepsPlayback: true, reenableSameSource: true })

  const releaseButton = page.getByRole('button', { name: '解除跟随', exact: true })
  // Snapshot at the actual click, since the followed planet keeps moving while automation waits.
  await releaseButton.evaluate(button => button.addEventListener('click', () => {
    window.__beforeAnchorReturn = { ...document.querySelector('.galaxy-viewport canvas').dataset }
  }, { capture: true, once: true }))
  await releaseButton.click()
  const beforeRelease = await page.evaluate(() => window.__beforeAnchorReturn)
  await expect(scene).toHaveAttribute('data-camera-follow-target', '')
  await expect(scene).toHaveAttribute('data-camera-anchor-returning', 'false', { timeout: 8000 })
  const afterRelease = await state()
  expect(Math.abs(Number(afterRelease.renderedZoom) - Number(beforeRelease.renderedZoom))).toBeLessThan(.01)
  expect(afterRelease.cameraMotionPreset).toBe(beforeRelease.cameraMotionPreset)
  expect(afterRelease.cameraFov).toBe(beforeRelease.cameraFov)
  const beforeQuaternion = JSON.parse(beforeRelease.cameraQuaternion), afterQuaternion = JSON.parse(afterRelease.cameraQuaternion)
  expect(Math.abs(beforeQuaternion.reduce((sum, value, i) => sum + value * afterQuaternion[i], 0))).toBeGreaterThan(.99999)
  await expect.poll(async () => {
    const d = await state(), star = JSON.parse(d.projectedTargets).find(target => target.id === '@album-star')
    return Math.hypot(star.x - 720, star.y - 450)
  }, { timeout: 8000 }).toBeLessThan(5)
  log({ releaseReturnsAnchorToStar: true, keepsZoomDirectionPresetAndFov: true })
  await page.keyboard.press('h')
  await page.getByRole('button', { name: '暂停动画', exact: true }).click()
  await expect(scene).toHaveAttribute('data-playing', 'false')
  await page.waitForTimeout(1400)
  const fixedCamera = await camera()
  await audio.evaluate(el => { el.currentTime = 14 })
  await expect.poll(() => numeric('audioHigh')).toBeGreaterThan(.003)
  samePose(await camera(), fixedCamera)
  log({ audioDoesNotMoveCamera: true })

  await page.mouse.move(300, 260); await page.mouse.down()
  for (let i = 1; i <= 10; i++) { await page.mouse.move(300 + i * 8, 260 + i); await page.waitForTimeout(45) }
  await expect(scene).toHaveAttribute('data-interaction-active', 'true')
  await expect.poll(() => numeric('particleRatio')).toBeLessThan(.65)
  await expect(scene).toHaveAttribute('data-post-enabled', 'true')
  const during = await state()
  expect(Number(during.renderDpr)).toBeLessThan(Number(during.baseDpr))
  await page.screenshot({ path: `${output}/interaction.png` })
  await page.mouse.up()
  await expect.poll(() => numeric('particleRatio'), { timeout: 8000 }).toBeGreaterThan(.997)
  await expect(scene).toHaveAttribute('data-quality-recovering', 'false')
  await expect(scene).toHaveAttribute('data-post-enabled', 'true')
  expect(await numeric('bloomIntensity')).toBeGreaterThan(.795)
  const after = await state()
  expect(Math.abs(Number(after.renderDpr) - Number(after.baseDpr))).toBeLessThanOrEqual(.026)
  expect(await scene.evaluate(el => el === window.__originalGalaxyCanvas)).toBe(true)
  log({ interactionBudgetAndRecovery: true, during: { ratio: during.particleRatio, bloom: during.bloomIntensity, dpr: during.renderDpr }, after: { ratio: after.particleRatio, bloom: after.bloomIntensity, dpr: after.renderDpr }, canvasRetained: true })

  await page.getByRole('button', { name: '画面品质', exact: true }).click()
  await page.locator('.quality-menu').getByRole('button', { name: '流畅', exact: true }).click()
  await expect.poll(() => numeric('baseDpr')).toBeLessThan(.82)
  await page.mouse.move(190, 180); await page.mouse.wheel(0, -100)
  await expect(scene).toHaveAttribute('data-interaction-active', 'true')
  await expect(scene).toHaveAttribute('data-quality-recovering', 'false', { timeout: 10000 })
  expect(await numeric('renderDpr')).toBeLessThan(.84)
  log({ recoveryRespectsLowQuality: true })

  await page.getByRole('button', { name: '继续动画', exact: true }).click()
  await effects('巡航'); await closeEffects()
  await expect(scene).toHaveAttribute('data-camera-motion-preset', 'cruise')
  await expect.poll(() => numeric('cameraMotionSpeed')).toBe(1)
  await page.keyboard.press('h')
  await expect(scene).toHaveAttribute('data-camera-auto-following', 'true', { timeout: 10000 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(scene).toHaveAttribute('data-reduced-motion', 'true')
  await expect.poll(() => numeric('cameraFollowSpeed')).toBe(0)
  await expect(scene).toHaveAttribute('data-camera-drifting', 'false')
  await expect(scene).toHaveAttribute('data-playing', 'false')
  const reducedPose = await camera(), timeAtReduce = await audio.evaluate(el => el.currentTime)
  await page.waitForTimeout(650)
  samePose(await camera(), reducedPose)
  expect(await audio.evaluate(el => el.currentTime)).toBeGreaterThan(timeAtReduce)
  await openEffects()
  await expect(page.locator('#universe-experience-menu').getByRole('button', { name: '巡航', exact: true })).toBeDisabled()
  await closeEffects()
  const beforeZoom = await numeric('renderedZoom')
  await page.mouse.move(190, 180); await page.mouse.wheel(0, 120)
  await expect.poll(() => numeric('renderedZoom')).toBeGreaterThan(beforeZoom)
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await expect(scene).toHaveAttribute('data-reduced-motion', 'false')
  await expect.poll(() => numeric('cameraMotionSpeed')).toBe(1)
  log({ runtimeReducedMotion: true, manualZoomAndAudioRetained: true, chosenPresetRestored: true })

  await effects('微动'); await closeEffects()
  await page.getByRole('button', { name: '跟随当前歌曲', exact: true }).click()
  await audio.evaluate(el => { el.currentTime = 3 })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByTestId('lyric-caption')).toHaveAttribute('data-view-mode', 'overview')
  await expect(page.locator('.lyric-row')).toHaveCount(4)
  await expect(page.locator('.lyric-row-distant')).toBeVisible()
  await page.mouse.move(95, 110)
  await wheelTo(.65, -1)
  await expect(page.getByTestId('lyric-caption')).toHaveAttribute('data-view-mode', 'near')
  await expect(page.locator('.lyric-row')).toHaveCount(2)
  const captionBox = await page.getByTestId('lyric-caption').boundingBox(), followBox = await page.getByTestId('planet-follow-control').boundingBox()
  expect(overlap(captionBox, followBox)).toBeFalsy()
  await openEffects(); await page.waitForTimeout(450)
  const effectsBox = await page.locator('#universe-experience-menu').boundingBox(), shiftedCaptionBox = await page.getByTestId('lyric-caption').boundingBox()
  expect(overlap(shiftedCaptionBox, effectsBox)).toBeFalsy()
  expect(effectsBox.x).toBeGreaterThanOrEqual(0)
  expect(effectsBox.x + effectsBox.width).toBeLessThanOrEqual(391)
  await closeEffects(); await page.waitForTimeout(450)
  await page.screenshot({ path: `${output}/mobile.png` })
  log({ mobileTwoAndFourRows: true, captionsAvoidFollowAndEffects: true })
  await page.getByRole('button', { name: '关闭星球详情', exact: true }).click()
  await expect(scene).toHaveAttribute('data-camera-follow-target', '')
  await expect(scene).toHaveAttribute('data-camera-anchor-returning', 'false', { timeout: 8000 })
  await expect(page.getByTestId('lyric-caption')).toHaveAttribute('data-view-mode', 'overview')
  log({ closeFollowCardAlsoReturnsStarAnchor: true })

  const soak = Math.max(0, Number(process.env.UNIVERSE_SOAK_SECONDS) || 0)
  if (soak) {
    await page.setViewportSize({ width: 1440, height: 900 })
    await audio.evaluate(el => { el.loop = true })
    const start = Date.now(), samples = [], perf = await page.context().newCDPSession(page)
    await perf.send('Performance.enable')
    while (Date.now() - start < soak * 1000) {
      await page.mouse.move(180, 180); await page.mouse.wheel(0, 30)
      await page.waitForTimeout(1600); await page.mouse.wheel(0, -30)
      await page.waitForTimeout(1600)
      const d = await state(), metrics = await perf.send('Performance.getMetrics')
      const heap = metrics.metrics.find(item => item.name === 'JSHeapUsedSize')?.value
      samples.push({ elapsed: Math.round((Date.now() - start) / 1000), heap, resources: JSON.parse(d.gpuResources), subscribers: Number(d.frameSubscribers), frames: Number(d.frameCount) })
      if (samples.length % 9 === 0) console.log(JSON.stringify({ soakProgress: samples.at(-1) }))
    }
    const late = samples.slice(Math.floor(samples.length / 2))
    expect(new Set(late.map(s => s.resources.geometries)).size).toBe(1)
    expect(new Set(late.map(s => s.resources.textures)).size).toBe(1)
    expect(Math.max(...late.map(s => s.subscribers)) - Math.min(...late.map(s => s.subscribers))).toBeLessThanOrEqual(1)
    expect(samples.at(-1).frames).toBeGreaterThan(samples[0].frames)
    expect(await moving()).toBe(true)
    writeFileSync(`${output}/soak.json`, JSON.stringify(samples, null, 2))
    log({ sustainedBrowseSeconds: soak, stableGpuResources: true, samples: samples.length, browserRenderer: 'headless Chromium with SwiftShader; not a hardware FPS benchmark' })
  }
  expect(errors).toEqual([])
  writeFileSync(`${output}/results.json`, JSON.stringify({ url, results, errors }, null, 2))
  console.log(JSON.stringify({ passed: results.length, errors }))
} catch (error) {
  await page.screenshot({ path: `${output}/failure.png` }).catch(() => {})
  writeFileSync(`${output}/failure.json`, JSON.stringify({ results, errors, state: await state().catch(() => ({})), error: String(error) }, null, 2))
  throw error
} finally { await browser.close() }
