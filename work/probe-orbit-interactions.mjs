import { chromium } from '@playwright/test'
const browser = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader'] })
const page = await browser.newPage({ viewport: { width: 1600, height: 900 } })
const read = () => page.locator('canvas').evaluate(element => ({ ...element.dataset }))
try {
  await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
  const overview = await read()
  await page.mouse.move(822, 450)
  await page.mouse.wheel(0, -500)
  await page.waitForTimeout(3200)
  const focused = await read()
  await page.screenshot({ path: 'work/orbit-reference-focus.png' })
  await page.mouse.move(800, 450)
  await page.mouse.down()
  await page.mouse.move(950, 465, { steps: 10 })
  await page.mouse.up()
  await page.waitForTimeout(400)
  const dragged = await read()
  await page.mouse.move(800, 450)
  await page.mouse.dblclick(800, 450, { delay: 120 })
  await page.waitForTimeout(800)
  const playback = await page.locator('audio').evaluate(element => ({ paused: element.paused, source: new URL(element.currentSrc).pathname }))
  await page.keyboard.press('Space')
  await page.mouse.wheel(0, 500)
  await page.waitForTimeout(100)
  await page.mouse.wheel(0, 500)
  await page.waitForTimeout(1600)
  const returned = await read()
  console.log(JSON.stringify({ overview, focused, dragged, playback, returned }, null, 2))
} finally { await browser.close() }
